#!/usr/bin/env python3
"""Install the foreground shelldeck command for the current user."""

import argparse
import os
from pathlib import Path
import shlex
import sys
import tempfile

PROJECT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT))
from shelldeck_config import read_config

HEADER = "#!/bin/sh\n# Generated by ShellDeck scripts/install.py\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, help="bind an existing ShellDeck JSON file; otherwise discover it at startup")
    parser.add_argument("--command-path", type=Path, default=Path.home() / ".local/bin/shelldeck")
    args = parser.parse_args()
    try:
        config = args.config.expanduser().resolve() if args.config is not None else None
        if config is not None:
            read_config(config, remote=False)
        command = args.command_path.expanduser().absolute()
        if command.is_symlink() or (command.exists() and not command.read_bytes().startswith(HEADER.encode())):
            raise ValueError(f"refusing to replace an unrelated command: {command}; choose --command-path")
        arguments = [sys.executable, str(PROJECT / "shelldeck.py")]
        if config is not None:
            arguments.extend(["--config", str(config)])
        wrapper = HEADER + "exec " + shlex.join(arguments) + ' "$@"\n'
        command.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
        fd, temporary = tempfile.mkstemp(prefix=".shelldeck-", dir=command.parent)
        try:
            with os.fdopen(fd, "w") as handle:
                handle.write(wrapper)
            os.chmod(temporary, 0o700)
            os.replace(temporary, command)
        finally:
            if os.path.exists(temporary):
                os.unlink(temporary)
        print(f"Installed {command}\nConfig: {config if config else 'auto-discovered at startup'}\n"
              "Start with: shelldeck --remote  OR  shelldeck --local -p 9099")
    except (OSError, ValueError) as error:
        parser.exit(1, f"shelldeck install: {error}\n")


if __name__ == "__main__":
    main()
