#!/usr/bin/env python3
"""Install the foreground shelldeck command for the current user."""

import argparse
import os
from pathlib import Path
import shlex
import sys
import tempfile

PROJECT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT))
from shelldeck_config import default_config, read_config

HEADER = "#!/bin/sh\n# Generated by ShellDeck scripts/install.py\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=default_config(), help="existing ShellDeck JSON configuration")
    parser.add_argument("--command-path", type=Path, default=Path.home() / ".local/bin/shelldeck")
    args = parser.parse_args()
    try:
        config = args.config.expanduser().resolve()
        endpoint = read_config(config)
        command = args.command_path.expanduser().absolute()
        if command.is_symlink() or (command.exists() and not command.read_bytes().startswith(HEADER.encode())):
            raise ValueError(f"refusing to replace an unrelated command: {command}; choose --command-path")
        wrapper = (HEADER + "exec "
                   + shlex.join([sys.executable, str(PROJECT / "shelldeck.py"), "--config", str(config)])
                   + ' "$@"\n')
        command.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
        fd, temporary = tempfile.mkstemp(prefix=".shelldeck-", dir=command.parent)
        try:
            with os.fdopen(fd, "w") as handle:
                handle.write(wrapper)
            os.chmod(temporary, 0o700)
            os.replace(temporary, command)
        finally:
            if os.path.exists(temporary):
                os.unlink(temporary)
        print(f"Installed {command}\nConfig: {config}\nListener: {endpoint['host']}:{endpoint['port']} (PROXY v1)")
    except (OSError, ValueError) as error:
        parser.exit(1, f"shelldeck install: {error}\n")


if __name__ == "__main__":
    main()
